// =============================================================
// scripts/compute-unpack-closure.mjs — asarUnpack 闭包清单生成器
//
// 安装时间由解包文件数主导（NSIS 逐文件解压 + 杀软逐文件扫描，实测
// 36.5s 基准里 36.3s 是落盘风暴，见 scripts/bench-install.mjs）。所以
// node_modules 不再整树解包（asarUnpack "**/node_modules/**" 是反模式）：
//
//   - 必须以真实文件落盘的：dsh 子进程的依赖闭包。dsh 后端由 staged
//     node.exe 跑（runtime.ts 把 Electron exe 改写成 dsh-node/node.exe），
//     纯 node 子进程看不见 app.asar，闭包内每个包都得在 app.asar.unpacked。
//   - 其余包只有 Electron 主进程用（openai/@aws-sdk/@anthropic-ai/...），
//     主进程读 asar 透明 —— 收进 app.asar，安装时变成 1 个大文件顺序写。
//   - 原生件（*.node/*.exe/*.dll）由 electron-builder smartUnpack 自动摘出。
//
// 本脚本从 node_modules/@deepseek-ai/dsh 出发 BFS 走真实 npm 平铺树的
// dependencies/optionalDependencies（peerDependencies 仅当树里真实存在），
// 并上固定保留项（pnpm 工具链 / pdfjs-dist 运行时按路径读资源），在
// electron-builder.yml 的哨兵块里重写 asarUnpack 清单，同时落一份
// build/unpack-closure.json 给 afterPack / verify-dsh-package 的守卫对照。
//
// 「@deepseek-ai」整体一条 pattern：dsh 是黑盒 SDK，除 package.json 声明的
// 依赖外还有 cordis 运行时按名装载的微包，scope 整体落盘最稳（见 yml 注释）。
//
// 用法: node scripts/compute-unpack-closure.mjs   （prepackage 链自动跑）
// 退出码: 0 成功, 1 失败
// =============================================================

import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs'
import { syncInstallLayout } from './lib/install-layout.mjs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const NM = join(ROOT, 'node_modules')
const YML = join(ROOT, 'electron-builder.yml')
const OUT_JSON = join(ROOT, 'build', 'unpack-closure.json')

const BEGIN = '# >>> unpack-closure (generated by scripts/compute-unpack-closure.mjs — 勿手改) >>>'
const END = '# <<< unpack-closure <<<'

/** dsh 闭包的根：staged node.exe 跑的就是它（runtime.ts resolveDshEntryPath）。 */
const CLOSURE_ROOT = '@deepseek-ai/dsh'
/** scope 整体落盘：黑盒 SDK + cordis 运行时按名装载，不能只信 package.json 声明。 */
const UNPACK_SCOPES = ['@deepseek-ai']
/**
 * 固定保留（非闭包但必须真实落盘）。
 *
 * 无 platform 的条目每个发布机构建都必须在。带 platform 的是 smartUnpack
 * 会整包解出的原生可选包：npm 对「有 os/cpu、没有 libc 字段」的可选依赖会把
 * 同一架构的 glibc 与 musl 两份都装上（linux x64 实测四件一起进
 * app.asar.unpacked），mac 则是磁盘上实际有的那些 darwin 架构（经常只有
 * 宿主架构，交叉安装时两份都在）。宿主自己的那一份缺失要失败；其余发布
 * 平台的变体装上了就入账，没装就跳过——不能只记 Windows，否则 linux/mac
 * 的 afterPack 守卫会把它们当成预料外解包。
 *
 * arch 用 Node 的 process.arch（x64 / arm64）。libc 只用来区分「宿主主包」
 * 和「同架构的另一份 libc」：musl 不是 ubuntu 构建的主包，但装上了必须入账。
 */
export const KEEPERS = [
  // 教师包不再保留 pnpm / @pnpm/exe（连接中心直接改写 profile 链接）。
  // PDF 套打光栅化运行时按路径读 cmaps/standard_fonts（pdf-rasterize.ts）
  { name: 'pdfjs-dist' },
  // 原生主进程包：smartUnpack 见 .node 会整包解出（主进程 dlopen 必须），
  // 显式写进清单让守卫账目对齐。新增原生依赖时守卫会再拦一次，照实补录。
  { name: 'better-sqlite3' },
  { name: '@napi-rs/canvas-win32-x64-msvc', platform: 'win32', arch: 'x64' },
  { name: '@napi-rs/canvas-darwin-x64', platform: 'darwin', arch: 'x64' },
  { name: '@napi-rs/canvas-darwin-arm64', platform: 'darwin', arch: 'arm64' },
  { name: '@napi-rs/canvas-linux-x64-gnu', platform: 'linux', arch: 'x64', libc: 'gnu' },
  { name: '@napi-rs/canvas-linux-x64-musl', platform: 'linux', arch: 'x64', libc: 'musl' },
]

/**
 * 宿主构建必须在位的保留项。另一份 libc、另一套 mac 架构、别的操作系统
 * 都不是硬性要求——那些只在 node_modules 里真有时才入账。
 */
export function isRequiredOnHost(keeper, platform, arch) {
  if (!keeper.platform) return true
  if (keeper.platform !== platform) return false
  if (keeper.arch && keeper.arch !== arch) return false
  if (keeper.libc === 'musl') return false
  return true
}

/**
 * 选出本次构建要写进 asarUnpack / unpack-closure.json 的保留包。
 * 装上了且会随包的平台变体一律入选（含 musl、含 mac 的另一架构）；
 * 宿主主包缺失或不随包则失败，避免带着空的 pnpm/canvas 原生件出货。
 */
export function selectKeepers(keepers, { platform, arch, exists, inShipSet }) {
  const selected = []
  for (const keeper of keepers) {
    const onDisk = exists(keeper.name)
    const shipped = onDisk && inShipSet(keeper.name)
    if (shipped) {
      selected.push(keeper.name)
      continue
    }
    if (isRequiredOnHost(keeper, platform, arch)) {
      return {
        ok: false,
        missing: keeper.name,
        reason: onDisk ? 'not-shipped' : 'missing',
        selected,
      }
    }
  }
  return { ok: true, selected }
}

/** 哨兵块内部的 asarUnpack 条目。只留操作系统必须映射的原生文件。 */
export function asarUnpackEntries() {
  return ['**/*.node', '**/*.dll', '**/*.exe', '**/*.dylib', '**/*.so'].map(
    (glob) => `  - "${glob}"`,
  )
}
/** files 负向过滤不随包的包（asarUnpack 写了也是空匹配，这里显式对齐账目）。 */
const NOT_SHIPPED = [
  '@deepseek-ai/libreoffice-kit-win32-x64',
  '@deepseek-ai/dsh-experimental-inspector',
  '@deepseek-ai/dsh-experimental-speech-to-text-sensevoice',
  '@deepseek-ai/dsh-experimental-liveshare',
  '@deepseek-ai/dsh-experimental-client-ui-forge',
  'sherpa-onnx-node',
  'sherpa-onnx-win-x64',
  'lxgw-wenkai-webfont',
  '@fontsource/jetbrains-mono',
  '@fontsource-variable/inter',
]

/** 闭包成员里 electron-builder 实测不发货的（对照 v3.3.6/v3.3.7 产物 7z 逐文件
 *  核对过）：yallist 是 lru-cache 的声明依赖，但 builder 的发货树里从未出现，
 *  旧包缺它一直正常。豁免必须逐个核实后录入；新名字冒出来时守卫会拦下，先查
 *  产物里到底有没有，再决定是补账目还是修依赖。 */
const KNOWN_BUILDER_SKIPS = new Set(['yallist'])

function fail(msg) {
  console.error(`[compute-unpack-closure] ${msg}`)
  process.exit(1)
}

const pkgDir = (name) => join(NM, ...name.split('/'))
const exists = (name) => existsSync(join(pkgDir(name), 'package.json'))

function readPkg(name) {
  try {
    return JSON.parse(readFileSync(join(pkgDir(name), 'package.json'), 'utf8'))
  } catch (err) {
    fail(`读 ${name}/package.json 失败：${err.message}`)
  }
}

function main() {
// ---- 0. shipSet：electron-builder 实际会随包的集合 ----
// 从根 package.json 的 dependencies 出发，只走 dependencies + optionalDependencies
// （不含 peerDependencies：npm 7+ 会自动安装 peer，但 builder 的发货树不走 peer，
// 实测该算法精确复现产物里的 715 个包）。落盘集合必须与它求交，否则清单里会
// 混进"dev 树里有、产物里根本没有"的包（dsh 体系大量 peer+dev 成对声明的
// 微包如 dsh-bash-local，v3.3.6 起就从不随包，运行时并不需要）。
const rootPkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'))
const shipSet = new Set()
const shipQueue = [...Object.keys(rootPkg.dependencies ?? {})]
while (shipQueue.length > 0) {
  const name = shipQueue.shift()
  if (shipSet.has(name) || !exists(name)) continue
  shipSet.add(name)
  const pkg = readPkg(name)
  for (const field of ['dependencies', 'optionalDependencies']) {
    shipQueue.push(...Object.keys(pkg[field] ?? {}))
  }
}

// ---- 1. BFS 依赖闭包 ----
const closure = new Set()
const queue = [CLOSURE_ROOT]
while (queue.length > 0) {
  const name = queue.shift()
  if (closure.has(name) || !exists(name)) continue
  closure.add(name)
  const pkg = readPkg(name)
  const depFields = ['dependencies', 'optionalDependencies']
  const deps = []
  for (const field of depFields) {
    for (const dep of Object.keys(pkg[field] ?? {})) deps.push(dep)
  }
  // peerDependencies 只在树里真实存在时才算（平铺树由宿主供给）
  for (const dep of Object.keys(pkg.peerDependencies ?? {})) {
    if (exists(dep)) deps.push(dep)
  }
  for (const dep of deps) {
    if (!exists(dep)) {
      // optionalDependencies 允许缺席（平台包/可省件）
      const optional = Object.keys(pkg.optionalDependencies ?? {}).includes(dep)
      if (!optional) fail(`闭包依赖缺失：${name} → ${dep}（node_modules 不完整？先 npm ci）`)
      continue
    }
    queue.push(dep)
  }
}
if (!exists(CLOSURE_ROOT)) fail(`找不到 ${CLOSURE_ROOT}（先 npm ci）`)

// ---- 2. 期望落盘清单：(scope 全体 + 闭包 + keepers) ∩ shipSet − 不随包 ----
const scopePkgs = []
for (const scope of UNPACK_SCOPES) {
  const dir = join(NM, scope)
  if (!existsSync(dir)) fail(`scope 目录缺失：${dir}`)
  for (const name of readdirSync(dir)) {
    if (exists(`${scope}/${name}`)) scopePkgs.push(`${scope}/${name}`)
  }
}
const keeperResult = selectKeepers(KEEPERS, {
  platform: process.platform,
  arch: process.arch,
  exists,
  inShipSet: (name) => shipSet.has(name),
})
if (!keeperResult.ok) {
  if (keeperResult.reason === 'not-shipped') {
    fail(`固定保留项 ${keeperResult.missing} 不在随包集合里（不再随包？更新 KEEPERS 或 files 配置）`)
  }
  fail(`固定保留项不在树里：${keeperResult.missing}（package.json 依赖变了？同步更新 compute-unpack-closure.mjs）`)
}
const keeperSet = keeperResult.selected
const notShipped = new Set(NOT_SHIPPED.filter((n) => exists(n)))
const candidates = [...new Set([...scopePkgs, ...closure, ...keeperSet])]
const unreachable = candidates.filter(
  (name) => !shipSet.has(name) && !notShipped.has(name) && !KNOWN_BUILDER_SKIPS.has(name),
)
const expectedUnpacked = candidates
  .filter(
    (name) =>
      shipSet.has(name) && !notShipped.has(name) && !KNOWN_BUILDER_SKIPS.has(name),
  )
  .sort()

// 真正会进 asar 的包 = shipSet − 落盘 − 不随包
const asarOnly = [...shipSet]
  .filter((name) => !expectedUnpacked.includes(name) && !notShipped.has(name))
  .sort()

// ---- 3. 文件数账目（装进 asar 的收益就是这些落盘文件消失）----
const countFiles = (dir) => {
  let n = 0
  const walk = (d) => {
    let entries
    try {
      entries = readdirSync(d)
    } catch {
      return
    }
    for (const name of entries) {
      const p = join(d, name)
      let st
      try {
        st = statSync(p)
      } catch {
        continue
      }
      if (st.isDirectory()) walk(p)
      else n += 1
    }
  }
  walk(dir)
  return n
}
let unpackedFiles = 0
for (const name of expectedUnpacked) unpackedFiles += countFiles(pkgDir(name))
let asarFiles = 0
for (const name of asarOnly) asarFiles += countFiles(pkgDir(name))

// ---- 4. 安装布局：asar 只解原生文件，dsh 闭包改走 runtime zip ----
// 旧的逐包 asarUnpack 会把一万多个 js 写成真实文件。electron-builder 的
// 依赖遍历又不带 peer，dsh-scope 这类包两边都没有。布局以 install-layout 为准。
const layout = syncInstallLayout(ROOT)
const platformKept = keeperSet.filter((name) => KEEPERS.some((k) => k.name === name && k.platform))
console.log(
  `[compute-unpack-closure] 随包依赖遍历 ${shipSet.size} 包；runtime zip ${layout.archive} 包，从安装目录排除 ${layout.exclude} 包（peer 不在依赖遍历里：${layout.peersOutsideShip.length}）`,
)
console.log(
  `[compute-unpack-closure] 平台原生保留 ${platformKept.length} 个：${platformKept.join(', ') || '（本机没有额外平台包）'}`,
)
}

function isDirectRun() {
  const entry = process.argv[1]
  if (!entry) return false
  try {
    return import.meta.url === pathToFileURL(entry).href
  } catch {
    return false
  }
}

if (isDirectRun()) main()
