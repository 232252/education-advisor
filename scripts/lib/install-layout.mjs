export function isHostPackage(name) {
  if (name.includes('win32') && process.platform !== 'win32') return false
  if (name.includes('darwin') && process.platform !== 'darwin') return false
  if (name.includes('linux') && process.platform !== 'linux') return false
  if (process.platform === 'linux') {
    let musl = false
    try {
      const report = process.report?.getReport?.()
      musl = !report?.header?.glibcVersionRuntime
    } catch {
      musl = false
    }
    if (musl && (name.includes('-gnu') || name.endsWith('.linux-x64'))) return false
    if (!musl && name.includes('musl')) return false
  }
  return true
}

const UNPACK_BEGIN = '# >>> install-layout-unpack (generated by scripts/lib/install-layout.mjs — 勿手改) >>>'
const UNPACK_END = '# <<< install-layout-unpack <<<'
const EXCLUDE_BEGIN = '# >>> install-layout-exclude (generated by scripts/lib/install-layout.mjs — 勿手改) >>>'
const EXCLUDE_END = '# <<< install-layout-exclude <<<'
const OLD_UNPACK_BEGIN = '# >>> unpack-closure'
const OLD_UNPACK_END = '# <<< unpack-closure <<<'

export function indexLock(lock) {
  const by = new Map()
  for (const [key, value] of Object.entries(lock.packages ?? {})) {
    if (!key.startsWith('node_modules/')) continue
    const name = key.slice('node_modules/'.length)
    if (name.includes('/node_modules/')) continue
    by.set(name, value)
  }
  // npm records a `file:` / workspace install as a `link: true` stub under
  // node_modules/<name> and keeps the real dependency list on the resolved
  // entry (vendor/pi-ai). Walking only the stub dropped
  // @earendil-works/pi-telemetry from the runtime zip, so official llm-pi-ai
  // could not mount (`no adapter registered`).
  for (const [name, value] of [...by.entries()]) {
    if (!value?.link) continue
    const resolved = value.resolved
    if (typeof resolved !== 'string' || resolved.length === 0) continue
    const target = lock.packages?.[resolved]
    if (target !== undefined) by.set(name, target)
  }
  return by
}

/**
 * @param {Map<string, any>} by
 * @param {string[]} seeds
 * @param {{ peers?: boolean }} [opts]
 */
export function walkPackages(by, seeds, opts = {}) {
  const seen = new Set()
  const queue = [...seeds]
  while (queue.length > 0) {
    const name = queue.pop()
    if (!name || seen.has(name) || !by.has(name)) continue
    seen.add(name)
    const meta = by.get(name)
    for (const field of ['dependencies', 'optionalDependencies']) {
      for (const dep of Object.keys(meta[field] ?? {})) queue.push(dep)
    }
    if (opts.peers) {
      const optional = meta.peerDependenciesMeta ?? {}
      for (const dep of Object.keys(meta.peerDependencies ?? {})) {
        if (optional[dep]?.optional && !by.has(dep)) continue
        queue.push(dep)
      }
    }
  }
  return seen
}

/** What electron-builder will actually copy. Peers are absent on purpose. */
export function dependencyShipSet(lock) {
  const by = indexLock(lock)
  const root = lock.packages?.[''] ?? {}
  return walkPackages(
    by,
    [...Object.keys(root.dependencies ?? {}), ...Object.keys(root.optionalDependencies ?? {})],
    { peers: false },
  )
}

/**
 * Packages the stock node child must see as real files after the runtime zip
 * is extracted. Includes the peer closure electron-builder would drop.
 */
export function runtimeArchivePackages(lock) {
  const by = indexLock(lock)
  const notShipped = new Set(NOT_SHIPPED)
  const archive = walkPackages(by, ['@deepseek-ai/dsh'], { peers: true })
  for (const name of by.keys()) {
    if (name.startsWith('@deepseek-ai/') && !notShipped.has(name)) archive.add(name)
  }
  for (const name of notShipped) archive.delete(name)
  // 教师运行时不带 pnpm / @pnpm/exe。仓库和 CI 打包机仍可用检出里的 pnpm，
  // 只是不能打进教师 zip 或安装包（连接中心改写 profile 链接，不再 plugin add）。
  // libreoffice-kit 也不进这个 STORE zip。Windows 那份是单独的 deflate zip；
  // darwin arm64 的 kit 约 161MB，放进来会让 macOS 的 runtime zip 超过预算。
  for (const name of [...archive]) {
    if (name === 'pnpm' || name.startsWith('@pnpm/exe')) archive.delete(name)
    if (name.startsWith('@deepseek-ai/libreoffice-kit')) archive.delete(name)
  }
  return archive
}

/** Zip payload for this machine. Other platforms' optional binaries stay out. */
export function hostRuntimePackages(lock) {
  const archive = runtimeArchivePackages(lock)
  for (const name of [...archive]) {
    if (!isHostPackage(name)) archive.delete(name)
  }
  return archive
}

function excludeCandidates(lock) {
  const names = new Set(runtimeArchivePackages(lock))
  for (const name of NOT_SHIPPED) names.add(name)
  for (const name of indexLock(lock).keys()) {
    if (name === 'pnpm' || name.startsWith('@pnpm/exe.') || name.startsWith('sherpa-onnx')) names.add(name)
    if (name.startsWith('@deepseek-ai/libreoffice-kit')) names.add(name)
  }
  return names
}

export function appKeepPackages(lock) {
  const by = indexLock(lock)
  const keep = walkPackages(by, APP_KEEP_ROOTS, { peers: false })
  // Packages that stay in app.asar still need their own dependency tree,
  // even when a dep is also in the dsh runtime archive. Stripping those
  // made 3.3.7-beta.2/beta.3 crash on startup (cross-spawn, then js-yaml).
  const wouldExclude = excludeCandidates(lock)
  for (const name of keep) wouldExclude.delete(name)
  const resident = [...dependencyShipSet(lock)].filter((name) => !wouldExclude.has(name))
  for (const name of walkPackages(by, resident, { peers: false })) keep.add(name)
  return keep
}

/** Archive members that must not also be loose files (or a second copy is only the keep set). */
export function filesToExclude(lock) {
  const keep = appKeepPackages(lock)
  return [...excludeCandidates(lock)].filter((name) => !keep.has(name)).sort()
}

export function asarUnpackEntries() {
  return NATIVE_GLOBS.map((glob) => `  - "${glob}"`)
}

export function fileExcludeEntries(names) {
  return names.map((name) => `  - "!node_modules/${name}/**"`)
}

function replaceSentinel(yml, beginNeedle, endNeedle, beginLine, endLine, body) {
  const beginAt = yml.indexOf(beginNeedle)
  const endAt = yml.indexOf(endNeedle)
  if (beginAt < 0 || endAt < 0 || endAt < beginAt) return null
  const lineStart = yml.lastIndexOf('\n', beginAt) + 1
  const endLineBreak = yml.indexOf('\n', endAt)
  return `${yml.slice(0, lineStart)}${beginLine}\n${body}\n${endLine}${yml.slice(endLineBreak)}`
}

export function syncInstallLayout(root) {
  const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'))
  const ship = dependencyShipSet(lock)
  const archive = runtimeArchivePackages(lock)
  const exclude = filesToExclude(lock)
  const missingPeers = LIVE_MISSING_PEERS.filter((name) => !archive.has(name))
  if (missingPeers.length > 0) {
    throw new Error(`runtime archive is missing required peers: ${missingPeers.join(', ')}`)
  }
  const missingRequired = RUNTIME_REQUIRED_PACKAGES.filter((name) => !archive.has(name))
  if (missingRequired.length > 0) {
    throw new Error(`runtime archive is missing required packages: ${missingRequired.join(', ')}`)
  }
  const stillShipped = LIVE_MISSING_PEERS.filter((name) => ship.has(name))
  // They must stay OUT of the dependency-only ship set. If a future builder
  // starts shipping them, the exclusion list still keeps a single copy in the zip.
  void stillShipped

  let yml = readFileSync(join(root, 'electron-builder.yml'), 'utf8')
  const unpackBody = asarUnpackEntries().join('\n')
  const excludeBody = fileExcludeEntries(exclude).join('\n')
  if (yml.includes(OLD_UNPACK_BEGIN) && !yml.includes(UNPACK_BEGIN)) {
    const migrated = replaceSentinel(yml, OLD_UNPACK_BEGIN, OLD_UNPACK_END, UNPACK_BEGIN, UNPACK_END, unpackBody)
    if (!migrated) throw new Error('electron-builder.yml unpack sentinel is malformed')
    yml = migrated
  }
  const unpacked = replaceSentinel(yml, UNPACK_BEGIN, UNPACK_END, UNPACK_BEGIN, UNPACK_END, unpackBody)
  if (!unpacked) throw new Error('electron-builder.yml is missing the install-layout-unpack sentinel')
  yml = unpacked
  if (!yml.includes(EXCLUDE_BEGIN)) {
    const anchor = '\nelectronLanguages:'
    const at = yml.indexOf(anchor)
    if (at < 0) throw new Error('electron-builder.yml is missing electronLanguages')
    yml = `${yml.slice(0, at)}\n${EXCLUDE_BEGIN}\n${excludeBody}\n${EXCLUDE_END}\n${yml.slice(at)}`
  } else {
    const excluded = replaceSentinel(yml, EXCLUDE_BEGIN, EXCLUDE_END, EXCLUDE_BEGIN, EXCLUDE_END, excludeBody)
    if (!excluded) throw new Error('electron-builder.yml exclude sentinel is malformed')
    yml = excluded
  }
  writeFileSync(join(root, 'electron-builder.yml'), yml)
  return {
    ship: ship.size,
    archive: archive.size,
    exclude: exclude.length,
    peersOutsideShip: LIVE_MISSING_PEERS.filter((name) => !ship.has(name)),
  }
}
