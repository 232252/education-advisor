// Which packages the Windows/mac/linux installer must keep out of the loose
// tree, and which ones Electron itself still has to load.
//
// electron-builder walks dependencies + optionalDependencies only. A blanket
// `node_modules/**` files glob does not ship peer-only packages. That is the
// v3.3.7-beta.1 failure: @deepseek-ai/dsh-scope (and 14 siblings) are
// peerDependencies, so they never entered app.asar or app.asar.unpacked.
// The same hole is called out in csthinker/deepseek-harness-desktop
// scripts/build-server.mjs (MIT): pnpm deploy with auto-install-peers=false
// drops dsh-scope, dsh-fs, and the rest of the peer closure.
//
// Smoke test on this tree (Electron 45.0.0, dsh 0.2.2-rc.1):
//   ELECTRON_RUN_AS_NODE=1 electron -e "require('node-addon-require-builtin').requireBuiltin('internal/modules/esm/loader')"
// rejects with "unsupported Electron runtime fingerprint" (supported:
// 43.0.0, 44.0.0, 44.7.0, 45.0.0-alpha.6). Stock node accepts it.
// So the child stays on vendor/dsh-node. The closure is one STORE zip,
// extracted under userData on first launch, not written file-by-file by NSIS.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

export const NATIVE_GLOBS = ['**/*.node', '**/*.dll', '**/*.exe', '**/*.dylib', '**/*.so']

